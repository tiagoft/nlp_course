"""Generate docs/contributions.md from the merged pull requests.

Uses the GitHub CLI (`gh`) to list the merged PRs in the repository and
builds an acknowledgments table with the date, the PR title (which is the
commit message of the contribution), and the username of the contributor.

Run it locally whenever you accept a pull request:

    python courseware/scripts/generate_contributions.py

and commit the updated docs/contributions.md.
"""

import json
import subprocess
from pathlib import Path

OUTPUT = Path(__file__).parent / ".." / "docs" / "contributions.md"

# Authors that are not listed in the acknowledgments table.
IGNORE = {"dependabot", "tiagoft"}

HEADER = """# Contributions

This material accepts contributions! We thank everyone who contributed
fixes, exercises, and improvements through pull requests!

Want to contribute too? See the step by step in [How to contribute](how_to_contribute.md).

<!-- File generated by courseware/scripts/generate_contributions.py. Do not edit by hand. -->
"""


def _merged_prs():
    output = subprocess.run(
        ["gh", "pr", "list", "--state", "merged", "--limit", "1000",
         "--json", "number,title,author,mergedAt,url"],
        check=True, capture_output=True, text=True,
    ).stdout
    prs = [p for p in json.loads(output) if p["author"]["login"] not in IGNORE]
    return sorted(prs, key=lambda p: p["mergedAt"], reverse=True)


def _cell(text):
    """Keep the text from breaking the markdown table."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _generate_markdown(prs):
    lines = [HEADER]
    if not prs:
        lines.append("No contributions yet. Be the first!")
        return "\n".join(lines) + "\n"

    authors = sorted({p["author"]["login"] for p in prs}, key=str.lower)
    lines.append("## Contributors\n")
    lines.append(", ".join(f"[@{a}](https://github.com/{a})" for a in authors) + "\n")

    lines.append("## Accepted contributions\n")
    lines.append("| Date | Contribution | Author |")
    lines.append("| --- | --- | --- |")
    for p in prs:
        date = p["mergedAt"][:10]
        login = p["author"]["login"]
        lines.append(
            f"| {date} | [{_cell(p['title'])}]({p['url']}) (#{p['number']}) "
            f"| [@{login}](https://github.com/{login}) |"
        )
    return "\n".join(lines) + "\n"


def main():
    prs = _merged_prs()
    OUTPUT.write_text(_generate_markdown(prs), encoding="utf-8")
    print(f"{OUTPUT.resolve()}: {len(prs)} contributions")


if __name__ == "__main__":
    main()
